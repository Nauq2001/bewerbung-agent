"""Alembic environment.

Runs migrations over a synchronous driver even though the application is
async. Alembic's migration context is synchronous, and DDL is a one-shot
operation at deploy time, so an async engine buys nothing and complicates
``alembic upgrade`` inside a container entrypoint.

The URL comes from DATABASE_URL, not alembic.ini, so the same file works
against a local Postgres and a Supabase project without edits.
"""

from __future__ import annotations

import os
from logging.config import fileConfig

from alembic import context
from sqlalchemy import engine_from_config, pool

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# Autogenerate is deliberately not wired to a MetaData object. These
# migrations are hand-written: the geo index, the generated tsvector column,
# the trigger and the seed rows are all things autogenerate cannot express,
# and a half-correct autogenerated diff is worse than none.
target_metadata = None


def _url() -> str:
    url = os.getenv("DATABASE_URL", "")
    if not url:
        raise RuntimeError(
            "DATABASE_URL is not set. Copy backend/.env.example and fill in the "
            "Supabase connection string."
        )
    # The app talks asyncpg; Alembic needs the sync driver for the same DSN.
    return url.replace("postgresql+asyncpg://", "postgresql+psycopg://")


def run_migrations_offline() -> None:
    context.configure(
        url=_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    section = config.get_section(config.config_ini_section, {})
    section["sqlalchemy.url"] = _url()
    connectable = engine_from_config(section, prefix="sqlalchemy.", poolclass=pool.NullPool)

    with connectable.connect() as connection:
        context.configure(connection=connection, target_metadata=target_metadata)
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
